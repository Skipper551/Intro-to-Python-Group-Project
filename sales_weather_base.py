"""sales_weather_base - shared starter module for the "Does the weather affect sales?" project.

Every group imports this module. It gives you:
    load_weather()        - London daily weather (from the JSON file) as a DataFrame
    load_transactions()   - Online Retail, cleaned with OUR class library `retail_tools`
    load_daily_sales()    - one row per day with sales (revenue, orders, customers, units)
    load_sales_weather()  - daily sales + weather in one table  <- most groups start here
    Analysis              - the parent class for your group's class
    expect_error()        - helper for testing that something raises an error

Do NOT edit this file - write your own code in your group's module.
"""
import json
import os

import pandas as pd

import retail_tools as rt                    # the library we built in classes 3+4
from retail_base import load_retail         # same file as in classes 3+4

WEATHER_FILE = "london_weather_2011.json"
SALES_FILE = "Online_Retail.csv"
DAILY_CACHE = "daily_sales.csv"              # created automatically the first time
WEEKDAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


# ---------------------------------------------------------------- loading
def load_weather(path=WEATHER_FILE):
    """Load the Open-Meteo JSON file and return one row per day.

    Returns:
        pd.DataFrame with a DatetimeIndex called "date" and the columns
        temp_mean, temp_max, temp_min [°C], rain_mm, snow_cm, sunshine_h, wind_kmh
    """
    with open(path, encoding="utf-8") as f:
        raw = json.load(f)                   # a dict - the data sits under raw["daily"]
    weather = pd.DataFrame(raw["daily"])
    weather = weather.rename(columns={
        "time": "date",
        "temperature_2m_mean": "temp_mean",
        "temperature_2m_max": "temp_max",
        "temperature_2m_min": "temp_min",
        "precipitation_sum": "rain_mm",      # rain + melted snow, in mm
        "snowfall_sum": "snow_cm",
        "wind_speed_10m_max": "wind_kmh",
    })
    weather["date"] = pd.to_datetime(weather["date"])          # JSON has no dates - only text
    weather["sunshine_h"] = (weather["sunshine_duration"] / 3600).round(1)   # seconds -> hours
    columns = ["temp_mean", "temp_max", "temp_min", "rain_mm", "snow_cm", "sunshine_h", "wind_kmh"]
    return weather.set_index("date")[columns]


def load_transactions(path=SALES_FILE):
    """Online Retail, cleaned with retail_tools.cleaning.clean_retail().

    One extra step (lesson from last class - the paper birds!): orders that were
    cancelled later are removed as well, not only the cancellation rows.

    Returns:
        pd.DataFrame, one row = one product line on an invoice
    """
    raw = load_retail(path)
    clean, _report = rt.cleaning.clean_retail(raw)
    cancelled = raw[raw["InvoiceNo"].str.startswith("C")].dropna(subset=["CustomerID"])
    cancelled_keys = set(zip(cancelled["CustomerID"].astype(int),
                             cancelled["StockCode"],
                             -cancelled["Quantity"]))
    keys = zip(clean["CustomerID"], clean["StockCode"], clean["Quantity"])
    was_cancelled = [k in cancelled_keys for k in keys]
    return clean[[not c for c in was_cancelled]].reset_index(drop=True)


def load_daily_sales(path=SALES_FILE, cache=DAILY_CACHE):
    """One row per day WITH SALES (days without any sales are not in the table!).

    The first call reads the big CSV (~20 s) and saves a small `daily_sales.csv`;
    later calls read the small file (fast).

    Returns:
        pd.DataFrame with a DatetimeIndex "date" and columns revenue, orders, customers, units
    """
    if cache and os.path.exists(cache):
        return pd.read_csv(cache, index_col="date", parse_dates=["date"])
    df = load_transactions(path)
    day = df["InvoiceDate"].dt.normalize().rename("date")
    daily = df.groupby(day).agg(revenue=("Revenue", "sum"),
                                orders=("InvoiceNo", "nunique"),
                                customers=("CustomerID", "nunique"),
                                units=("Quantity", "sum"))
    daily["revenue"] = daily["revenue"].round(2)
    if cache:
        daily.to_csv(cache)
    return daily


def load_sales_weather():
    """Daily sales + weather in one table (only days that have sales).

    Returns:
        pd.DataFrame indexed by date with: revenue, orders, customers, units,
        temp_mean, temp_max, temp_min, rain_mm, snow_cm, sunshine_h, wind_kmh,
        weekday (e.g. "Monday"), month (1-12)
    """
    data = load_daily_sales().join(load_weather(), how="inner")
    data["weekday"] = data.index.day_name()
    data["month"] = data.index.month
    return data


# ---------------------------------------------------------------- the parent class
class Analysis:
    """Parent class for every group's analysis (works like scikit-learn: create -> fit -> use).

    Your class inherits from it:

        class RainEffect(Analysis):
            required_columns = ["revenue", "rain_mm"]
            def fit(self):
                ...                       # compute something from self.data
                self.results_ = ...       # store the result
                return self

    What you get for free:
        self.data        - a COPY of the DataFrame you passed in (safe to change)
        self.results_    - None until fit() stores something there
        check_fitted()   - raises RuntimeError if fit() was not called yet
        print(obj)       - shows e.g. RainEffect(305 rows, fitted)
    """
    required_columns = []

    def __init__(self, data):
        if not isinstance(data, pd.DataFrame):
            raise TypeError("data must be a pandas DataFrame")
        missing = [c for c in self.required_columns if c not in data.columns]
        if missing:
            raise ValueError(f"data is missing the columns {missing}")
        self.data = data.copy()
        self.results_ = None

    def fit(self):
        raise NotImplementedError("every group writes its own fit() method")

    def check_fitted(self):
        if self.results_ is None:
            raise RuntimeError(f"call .fit() first - {type(self).__name__} is not fitted yet")

    def __repr__(self):
        status = "fitted" if self.results_ is not None else "not fitted"
        return f"{type(self).__name__}({len(self.data)} rows, {status})"


# ---------------------------------------------------------------- testing helper
def expect_error(func, *args, error=ValueError, **kwargs):
    """Return True if func(*args, **kwargs) raises `error`; otherwise raise AssertionError.

    Usage in tests:
        assert expect_error(RainEffect, "not a dataframe", error=TypeError)
        assert expect_error(model.predict, ["2011-12-01"], error=RuntimeError)
    """
    try:
        func(*args, **kwargs)
    except error:
        return True
    raise AssertionError(f"{getattr(func, '__name__', func)} did NOT raise {error.__name__}")
